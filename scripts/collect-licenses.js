'use strict';
/**
 * Assemble THIRD-PARTY-LICENSES.md from what the packaged app actually ships.
 *
 * Depending on a package via npm redistributes nothing -- node_modules is not
 * committed. Shipping a .app is different: Electron, Chromium, pdf-lib, pdf.js,
 * fontkit and the font all travel inside the bundle, and MIT, Apache-2.0 and the
 * OFL each require their notice to travel with them. @electron/packager writes
 * Electron's own notices *beside* the bundle in dist/, so handing someone just
 * Marginalia.app leaves them behind. This gathers everything into one file that
 * install-app.js puts inside Contents/Resources/.
 *
 * Reads each licence from the installed package rather than restating it, so it
 * cannot drift from what is on disk. Run: node scripts/collect-licenses.js
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'THIRD-PARTY-LICENSES.md');

/** Runtime dependencies -- the ones that end up inside the bundle. */
const SHIPPED = ['electron', 'pdf-lib', 'pdfjs-dist', '@pdf-lib/fontkit'];
const LICENCE_NAMES = ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'LICENCE', 'license'];

function readLicence(dir) {
  for (const n of LICENCE_NAMES) {
    const p = path.join(dir, n);
    if (fs.existsSync(p)) return fs.readFileSync(p, 'utf8').trim();
  }
  return null;
}

const parts = [`# Third-party licences

Marginalia itself is MIT licensed — see [LICENSE](LICENSE). The packaged
application bundles the components below, each under its own licence, reproduced
here in full as those licences require.

Generated by \`scripts/collect-licenses.js\` from the packages installed at build
time. Do not edit by hand.
`];

const missing = [];
for (const name of SHIPPED) {
  const dir = path.join(ROOT, 'node_modules', name);
  if (!fs.existsSync(dir)) { missing.push(`${name} (not installed)`); continue; }
  const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
  const text = readLicence(dir);
  const where = pkg.homepage || pkg.repository?.url || '';
  if (text) {
    parts.push(`\n---\n\n## ${name} ${pkg.version}\n\n` +
      `${where}\nLicence: ${pkg.license}\n\n` + '```\n' + text + '\n```\n');
  } else if (pkg.license) {
    // Some packages declare a licence but ship no licence file and no copyright
    // line. There is nothing to reproduce, so say that plainly rather than
    // inventing a notice that is not in the package.
    parts.push(`\n---\n\n## ${name} ${pkg.version}\n\n${where}\n` +
      `Licence: ${pkg.license} (declared in package.json)\n\n` +
      `This package ships no licence file and states no copyright holder, so no\n` +
      `notice could be reproduced here. See the project above for its terms.\n`);
  } else {
    missing.push(`${name} (no licence declared at all)`);
  }
}

// Chromium ships inside Electron; its notices are a separate, very large file
// that the packager emits next to the bundle.
parts.push(`\n---\n\n## Chromium\n
Electron embeds Chromium, whose licences are listed in \`LICENSES.chromium.html\`,
shipped alongside this file.\n`);

// The font is ours to ship, but only under the OFL, which requires its notice.
const ofl = path.join(ROOT, 'assets', 'fonts', 'OFL.txt');
if (fs.existsSync(ofl)) {
  parts.push(`\n---\n\n## EB Garamond\n
https://github.com/octaviopardo/EBGaramond12
Licence: SIL Open Font License 1.1\n\n` +
    '```\n' + fs.readFileSync(ofl, 'utf8').trim() + '\n```\n');
} else missing.push('EB Garamond OFL.txt');

// Not shipped in the bundle, but the palette came from them and MIT asks that
// the notice travel with any substantial portion. Cheap to be generous here.
parts.push(`\n---\n\n## Excalidraw and Open Color (colour palette)\n
No Excalidraw code is used. The five stroke colours and four highlighter colours
in \`renderer/app.js\` are Excalidraw's default picks from
\`packages/common/src/colors.ts\`, and the discrete stroke-width and font-size
steps follow their interface. Excalidraw takes those colour values from Open
Color.

- Excalidraw — MIT, Copyright (c) 2020 Excalidraw — https://github.com/excalidraw/excalidraw
- Open Color — MIT, Copyright (c) 2016 heeyeun — https://github.com/yeun/open-color
`);

fs.writeFileSync(OUT, parts.join(''));

if (missing.length) {
  console.error(`collect-licenses: could not include ${missing.join(', ')}`);
  process.exit(1);
}
console.log(`wrote ${path.relative(ROOT, OUT)} (${SHIPPED.length + 2} components)`);
